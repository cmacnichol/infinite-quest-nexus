import { randomBytes } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { setTimeout as delay } from "node:timers/promises";
import { spawn } from "node:child_process";
import { Client } from "pg";

const TEST_DATABASE_NAME = "infinitequest_test";
const TEST_DATABASE_USER = "infinitequest_test";
const TEST_DATABASE_HOST = "127.0.0.1";
const TEST_DATABASE_PORT = 55432;
const TEST_COMPOSE_PROJECT = "infinitequest-test";
const TEST_COMPOSE_FILE = "compose.test.yaml";
const TEST_ENVIRONMENT_FILE = ".env.test.local";
const STARTUP_ATTEMPTS = 120;
const STARTUP_DELAY_MS = 250;

export function dockerCommandForPlatform(platform = process.platform) {
  return platform === "win32" ? "docker.exe" : "docker";
}

function parseEnvironmentFile(contents) {
  return Object.fromEntries(contents.split(/\r?\n/u)
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const separator = line.indexOf("=");
      return separator === -1 ? [line, ""] : [line.slice(0, separator), line.slice(separator + 1)];
    }));
}

function databaseUrl(password, databaseName) {
  return `postgresql://${TEST_DATABASE_USER}:${encodeURIComponent(password)}@${TEST_DATABASE_HOST}:${TEST_DATABASE_PORT}/${databaseName}`;
}

function renderEnvironmentFile(password) {
  return [
    "# Generated by scripts/ensure-test-database.mjs. This file is ignored by Git.",
    `POSTGRES_USER=${TEST_DATABASE_USER}`,
    `POSTGRES_DB=${TEST_DATABASE_NAME}`,
    `POSTGRES_PASSWORD=${password}`,
    `TEST_POSTGRES_PORT=${TEST_DATABASE_PORT}`,
    `TEST_DATABASE_URL=${databaseUrl(password, TEST_DATABASE_NAME)}`,
    ""
  ].join("\n");
}

export async function loadTestDatabaseConfig(projectRoot, { generatePassword = () => randomBytes(32).toString("base64url") } = {}) {
  const environmentFile = join(projectRoot, TEST_ENVIRONMENT_FILE);
  let values = {};
  try {
    values = parseEnvironmentFile(await readFile(environmentFile, "utf8"));
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }

  const password = values.POSTGRES_PASSWORD || generatePassword();
  const expectedContents = renderEnvironmentFile(password);
  if (values.POSTGRES_PASSWORD !== password || values.TEST_DATABASE_URL !== databaseUrl(password, TEST_DATABASE_NAME)) {
    await writeFile(environmentFile, expectedContents, "utf8");
  }

  return {
    databaseName: TEST_DATABASE_NAME,
    databaseUrl: databaseUrl(password, TEST_DATABASE_NAME),
    adminDatabaseUrl: databaseUrl(password, "postgres"),
    environmentFile
  };
}

function runCommand(command, argumentsList, options) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, argumentsList, {
      cwd: options.cwd,
      stdio: "inherit",
      windowsHide: true
    });
    child.once("error", reject);
    child.once("exit", (code) => {
      if (code === 0) resolvePromise();
      else reject(new Error(`${command} exited with code ${code ?? "unknown"}.`));
    });
  });
}

async function connectWhenReady(createClient, adminDatabaseUrl, sleep) {
  let lastError;
  for (let attempt = 0; attempt < STARTUP_ATTEMPTS; attempt += 1) {
    const client = createClient(adminDatabaseUrl);
    try {
      await client.connect();
      return client;
    } catch (error) {
      lastError = error;
      await client.end().catch(() => undefined);
      await sleep(STARTUP_DELAY_MS);
    }
  }
  throw new Error(
    `The local PostgreSQL test database did not become ready after ${STARTUP_ATTEMPTS * STARTUP_DELAY_MS / 1000} seconds: ${lastError instanceof Error ? lastError.message : "unknown connection error"}`
  );
}

export async function ensureTestDatabase({
  projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), ".."),
  execute = runCommand,
  createClient = (connectionString) => new Client({ connectionString }),
  generatePassword,
  sleep = delay
} = {}) {
  const config = await loadTestDatabaseConfig(projectRoot, { generatePassword });
  const composeFile = join(projectRoot, TEST_COMPOSE_FILE);
  try {
    await execute(dockerCommandForPlatform(), [
      "compose",
      "--env-file", config.environmentFile,
      "--project-name", TEST_COMPOSE_PROJECT,
      "--file", composeFile,
      "up", "--detach", "integration-postgres"
    ], { cwd: projectRoot });
  } catch (error) {
    throw new Error(
      `Unable to start the local PostgreSQL test database. Start Docker Engine and rerun the test. ${error instanceof Error ? error.message : ""}`.trim()
    );
  }

  const client = await connectWhenReady(createClient, config.adminDatabaseUrl, sleep);
  try {
    const existing = await client.query("SELECT datname FROM pg_database WHERE datname = 'infinitequest_test'");
    if (existing.rows.length === 0) {
      await client.query('CREATE DATABASE "infinitequest_test"');
    }
  } finally {
    await client.end();
  }
  return config;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await ensureTestDatabase();
}
