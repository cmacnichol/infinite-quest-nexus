import { beforeAll, afterAll, describe, it, expect } from "vitest";
import { resolve } from "node:path";
import { createDatabasePool, initialOwnerId, type DatabasePool } from "../../packages/database/src/pool.js";
import { migrateDatabase } from "../../packages/database/src/migrate.js";
import { settingsFixture } from "../fixtures/instance-settings.js";
const url = process.env.TEST_DATABASE_URL;
(url ? describe : describe.skip)("installation settings persistence", () => {
  let pool: DatabasePool;
  beforeAll(async () => { pool = createDatabasePool(url!); await migrateDatabase(pool, resolve("database/migrations")); });
  afterAll(async () => { await pool?.end(); });
  it("binds expiring digest-only operator sessions and bounds durable unlock accounting", async () => {
    const { createSettingsOperatorRepository } = await import("../../packages/database/src/settings-operator-repository.js");
    const repository = createSettingsOperatorRepository(pool);
    const actorUserId = await initialOwnerId(pool);
    const session = await repository.createSession({ actorUserId, tokenDigest: "1".repeat(64), csrfDigest: "2".repeat(64), keyFingerprint: "3".repeat(64), expiresAt: new Date(Date.now()+600000) });
    expect(await repository.findSession({ tokenDigest: session.tokenDigest, actorUserId, keyFingerprint: session.keyFingerprint })).toMatchObject({ id: session.id });
    expect(await repository.findSession({ tokenDigest: session.tokenDigest, actorUserId: "00000000-0000-4000-8000-000000000099", keyFingerprint: session.keyFingerprint })).toBeNull();
    expect(await repository.findSession({ tokenDigest: session.tokenDigest, actorUserId, keyFingerprint: "4".repeat(64) })).toBeNull();
    await expect(repository.createSession({ ...session, expiresAt: new Date(Date.now()+3600000) })).rejects.toThrow();
    const attempts = await Promise.all(Array.from({ length: 12 }, () => repository.recordUnlockAttempt("5".repeat(64), "failure")));
    expect(attempts.filter(Boolean)).toHaveLength(5);
    expect((await pool.query("SELECT count(*)::int AS n FROM settings_unlock_attempts")).rows[0].n).toBe(2);
    await repository.revokeSession(session.id);
    expect(await repository.findSession({ tokenDigest: session.tokenDigest, actorUserId, keyFingerprint: session.keyFingerprint })).toBeNull();
    const expiring = await repository.createSession({ actorUserId, tokenDigest: "6".repeat(64), csrfDigest: "7".repeat(64), keyFingerprint: "8".repeat(64), expiresAt: new Date(Date.now()+600000) });
    await pool.query("UPDATE settings_operator_sessions SET created_at=clock_timestamp()-interval '20 minutes', expires_at=clock_timestamp()-interval '10 minutes' WHERE id=$1", [expiring.id]);
    expect(await repository.findSession({ tokenDigest: expiring.tokenDigest, actorUserId, keyFingerprint: expiring.keyFingerprint })).toBeNull();
    await repository.cleanup();
    expect((await pool.query("SELECT count(*)::int AS n FROM settings_operator_sessions")).rows[0].n).toBe(0);
    await pool.query("UPDATE settings_unlock_attempts SET attempts=50 WHERE bucket='global'");
    expect(await repository.recordUnlockAttempt("9".repeat(64), "failure")).toBe(false);
    expect((await pool.query("SELECT count(*)::int AS n FROM settings_unlock_attempts")).rows[0].n).toBe(2);
  });
  it("counts only failures and retains the five-client failure lock for fifteen minutes", async () => {
    await pool.query("DELETE FROM settings_unlock_attempts");
    const { createSettingsOperatorRepository } = await import("../../packages/database/src/settings-operator-repository.js");
    const repository = createSettingsOperatorRepository(pool);
    const client = "a".repeat(64);
    for (let index = 0; index < 8; index++) expect(await repository.recordUnlockAttempt(client, "success")).toBe(true);
    expect((await pool.query("SELECT count(*)::int AS n FROM settings_unlock_attempts")).rows[0].n).toBe(0);
    const attempts = await Promise.all(Array.from({ length: 12 }, () => repository.recordUnlockAttempt(client, "failure")));
    expect(attempts.filter(Boolean)).toHaveLength(5);
    expect((await pool.query("SELECT attempts FROM settings_unlock_attempts WHERE bucket='global'")).rows[0].attempts).toBe(5);
    await pool.query("UPDATE settings_unlock_attempts SET window_start=clock_timestamp()-interval '14 minutes 59 seconds'");
    expect(await repository.recordUnlockAttempt(client, "failure")).toBe(false);
    expect(await repository.recordUnlockAttempt(client, "success")).toBe(false);
    await pool.query("UPDATE settings_unlock_attempts SET window_start=clock_timestamp()-interval '15 minutes 1 second'");
    expect(await repository.recordUnlockAttempt(client, "success")).toBe(true);
    expect(await repository.recordUnlockAttempt(client, "failure")).toBe(true);
    expect((await pool.query("SELECT attempts FROM settings_unlock_attempts WHERE bucket='global'")).rows[0].attempts).toBe(1);
  });
  it("atomically admits at most fifty global failures across repositories and denies valid keys while exhausted", async () => {
    await pool.query("DELETE FROM settings_unlock_attempts");
    const { createSettingsOperatorRepository } = await import("../../packages/database/src/settings-operator-repository.js");
    const otherPool = createDatabasePool(url!);
    try {
      const repositories = [createSettingsOperatorRepository(pool), createSettingsOperatorRepository(otherPool)];
      const admitted = await Promise.all(Array.from({ length: 65 }, (_, index) => repositories[index % 2]!.recordUnlockAttempt(index.toString(16).padStart(64, "0"), "failure")));
      expect(admitted.filter(Boolean)).toHaveLength(50);
      const repository = repositories[0]!;
      expect(await repository.recordUnlockAttempt("f".repeat(64), "success")).toBe(false);
      expect((await pool.query("SELECT attempts FROM settings_unlock_attempts WHERE bucket='global'")).rows[0].attempts).toBe(50);
      expect((await pool.query("SELECT count(*)::int AS n FROM settings_unlock_attempts")).rows[0].n).toBe(51);
      await pool.query("UPDATE settings_unlock_attempts SET window_start=clock_timestamp()-interval '15 minutes 1 second'");
      expect(await repository.recordUnlockAttempt("f".repeat(64), "success")).toBe(true);
    } finally { await otherPool.end(); }
  });
  it("creates only environment mode during migration", async () => {
    const result = await pool.query("SELECT mode,active_revision,requested_revision FROM instance_settings_state");
    expect(result.rows).toEqual([{ mode: "environment", active_revision: null, requested_revision: null }]);
  });
  it("seeds idempotently, serializes proposals, appends rollback, protects immutable evidence and activates atomically", async () => {
    const { createInstanceSettingsRepository } = await import("../../packages/database/src/instance-settings-repository.js");
    const repository = createInstanceSettingsRepository(pool, { activationGuard: async (client, state) => { expect((await client.query("SELECT txid_current() AS id")).rows[0].id).toBeDefined(); expect(state.requestedRevision).toBe("3"); } });
    const actor = { userId: await initialOwnerId(pool), cliReference: "test-maintenance" };
    const seed = { installationId: "00000000-0000-4000-8000-000000000001", snapshot: settingsFixture(), policyDigest: "a".repeat(64), seedDigest: "b".repeat(64), actor };
    const first = await repository.seed(seed);
    expect(first).toMatchObject({ mode: "environment", activeRevision: null, requestedRevision: "1" });
    expect(await repository.seed(seed)).toEqual(first);
    await expect(repository.seed({ ...seed, seedDigest: "c".repeat(64) })).rejects.toThrow("seed_mismatch");
    const proposal = { expectedRequestedRevision: "1", snapshot: { ...seed.snapshot, logLevel: "debug" as const }, actor, reason: "operator_change" };
    const results = await Promise.allSettled([repository.propose(proposal), repository.propose(proposal)]);
    expect(results.filter((result) => result.status === "fulfilled")).toHaveLength(1);
    expect(results.filter((result) => result.status === "rejected")).toHaveLength(1);
    await repository.propose({ ...proposal, expectedRequestedRevision: "2" });
    expect((await pool.query("SELECT count(*)::int AS n FROM instance_settings_events")).rows[0].n).toBe(2);
    const rollback = await repository.propose({ ...proposal, expectedRequestedRevision: "2", snapshot: seed.snapshot, kind: "rollback" });
    expect(rollback.requestedRevision).toBe("3");
    await expect(pool.query("UPDATE instance_settings_revisions SET snapshot='{}' WHERE revision=1")).rejects.toThrow();
    await expect(pool.query("DELETE FROM instance_settings_events")).rejects.toThrow();
    await expect(repository.propose({ ...proposal, expectedRequestedRevision: "3", snapshot: { ...seed.snapshot, token: "secret" } as any })).rejects.toThrow();
    const activation = { expectedActiveRevision: null, expectedRequestedRevision: "3", policyDigest: seed.policyDigest, maintenanceReference: "drained-test", actor };
    await expect(createInstanceSettingsRepository(pool).activate(activation)).rejects.toThrow("activation_guard_required");
    await expect(createInstanceSettingsRepository(pool, { activationGuard: async () => { throw new Error("leases_remain"); } }).activate(activation)).rejects.toThrow("leases_remain");
    expect((await repository.read()).mode).toBe("environment");
    const active = await repository.activate({ expectedActiveRevision: null, expectedRequestedRevision: "3", policyDigest: seed.policyDigest, maintenanceReference: "drained-test", actor });
    expect(active).toMatchObject({ mode: "database", activeRevision: "3", requestedRevision: "3", activationEpoch: "1" });
    expect((await pool.query("SELECT maintenance_reference FROM instance_settings_events WHERE kind='activation'")).rows[0].maintenance_reference).toBe("drained-test");
  });
});
