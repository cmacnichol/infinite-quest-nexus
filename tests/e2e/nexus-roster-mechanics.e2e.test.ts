for (const count of [4, 1000]) test(`authored roster identities, filters and capacity at ${count}`, async ({ page }) => {
  const fixture = legacyUiFixture({ turnCount: 0, worldCount: 1, campaignCount: 0 });
  const detail = fixture.worldDetails.get(fixture.worldId)!;
  const content = detail.draftContent as any;
  const summary = "漢字مرحبا" + "x".repeat(200);
  content.playableCharacters = Array.from({ length: count }, (_, index) => ({ id: `person-${index}`, name: "Same", campaignUse: ["playable", "supporting", "both"][index % 3], characterText: "", profile: { identity: { aliases: [index === 1 ? "Watcher" : "Other"] }, story: { role: "Guide", personality: summary } }, rpgStats: [], defaultTriggers: [], source: {} }));
  const api = await installLegacyUiFixture(page, fixture);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("http://127.0.0.1:43173/nexus/index.html#world-library");
  await page.locator(`#worldManagementCarousel [data-world-id="${fixture.worldId}"]`).click();
  await page.locator("#editWorldDraft").click(); await page.locator('[data-world-author-step="character"]').click();
  const rows = page.locator(".character-roster-row");
  expect(await rows.evaluateAll(nodes => nodes.slice(0, 4).map(node => (node as HTMLElement).dataset.characterId))).toEqual(["person-0", "person-1", "person-2", "person-3"]);
  expect(await page.locator("#worldAuthorDialog").evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await page.getByRole("searchbox", { name: "Search characters" }).fill("watcher"); await expect(rows).toHaveCount(1);
  await page.getByRole("combobox", { name: "Filter character use" }).selectOption("both"); await expect(rows).toHaveCount(0);
  await page.getByRole("button", { name: "Clear filters", exact: true }).click();
  if (count === 1000) {
    await page.locator("#addPlayableCharacter").click(); await page.locator("#characterName").fill("Retained draft"); await page.locator("#characterRole").fill("Guide");
    await page.locator("#saveCharacter").click(); await expect(page.locator("#characterDialog")).toBeVisible();
    await expect(page.locator("#characterName")).toHaveValue("Retained draft"); await expect(page.locator(".character-quick-create").getByRole("status")).toContainText("full");
  } else {
    await page.getByRole("button", { name: "Duplicate Same", exact: true }).first().click();
    await expect(rows).toHaveCount(5);
    const ids = await rows.evaluateAll(nodes => nodes.map(node => (node as HTMLElement).dataset.characterId)); expect(new Set(ids).size).toBe(5);
    expect(content.playableCharacters[0].profile.story.personality).toBe(summary);
  }
  expect(api.writes).toHaveLength(0);
});

test("mechanics Undo restores imported extension and position and next removal replaces it", async ({ page }) => {
  const fixture = legacyUiFixture({ turnCount: 0, worldCount: 1, campaignCount: 0 });
  const content = fixture.worldDetails.get(fixture.worldId)!.draftContent as any;
  const stats = [{ id: "s1", skill: "Resolve", score: 12, covers: "One\nTwo", extra: { imported: true } }, { id: "s2", name: "Focus", value: 20, extra: [1, 2] }];
  const trackers = [{ id: "t1", label: "Oil", initialValue: "First\nSecond", updateRules: "At dusk\nAt dawn", extra: "kept" }];
  content.playableCharacters = [{ id: "mechanic-owner", name: "Mira", characterText: "Guide", campaignUse: "both", rpgStats: stats, defaultTriggers: trackers, source: { imported: true } }];
  const api = await installLegacyUiFixture(page, fixture);
  await page.goto("http://127.0.0.1:43173/nexus/index.html#world-library");
  await page.locator(`#worldManagementCarousel [data-world-id="${fixture.worldId}"]`).click(); await page.locator("#editWorldDraft").click();
  await page.locator('[data-world-author-step="character"]').click(); await page.getByRole("button", { name: "Edit Mira", exact: true }).click();
  await page.getByRole("navigation", { name: "Character sections" }).getByRole("button", { name: /^Mechanics ·/ }).click();
  await page.locator("#characterMechanics").evaluate((node: HTMLDetailsElement) => node.open = true);
  await expect(page.locator('#characterTrackers textarea[data-character-field=value]')).toHaveValue("First\nSecond");
  await expect(page.locator('#characterTrackers textarea[data-character-field=rules]')).toHaveValue("At dusk\nAt dawn");
  await page.getByRole("button", { name: "Remove Resolve statistic" }).click(); await page.getByRole("button", { name: "Undo removal" }).click();
  await expect(page.locator('#characterStats [data-character-field=name]').first()).toHaveValue("Resolve");
  await page.getByRole("button", { name: "Remove Focus statistic" }).click(); await page.getByRole("button", { name: "Remove Oil tracker" }).click();
  await page.getByRole("button", { name: "Undo removal" }).click(); await expect(page.getByRole("button", { name: "Undo removal" })).toHaveCount(0);
  await expect(page.locator('#characterStats .character-edit-row')).toHaveCount(1);
  await page.locator("#saveCharacter").click(); await page.locator("#saveWorldDraft").click();
  const saved = api.writes.find(write => write.path.endsWith("/draft"))?.body as any;
  expect(saved.content.playableCharacters[0].rpgStats).toEqual([stats[0]]);
  expect(saved.content.playableCharacters[0].defaultTriggers).toEqual(trackers);
});
