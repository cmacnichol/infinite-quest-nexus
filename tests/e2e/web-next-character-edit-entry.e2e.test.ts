import { expect, test } from "@playwright/test";
import { mockAuthoringSession } from "./helpers/authoring-session.js";

test.beforeEach(mockAuthoringSession);
for (const width of [1280, 390]) test(`existing world character opens Review at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 });
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const draft = { schemaVersion: 5, world: { title: "Glass Atlas", genre: "", tone: "", premise: "", backgroundStory: "", firstAction: "", rules: "" }, playableCharacters: [], entities: [], relationships: [], rpgStats: [], defaultTriggers: [], eventTriggers: [], assets: [], defaults: {} };
  const candidate = { id: "hero", name: "Ilyra", characterText: "", campaignUse: "playable", startingCastDefault: true, alwaysInContext: false, rpgStats: [], defaultTriggers: [], source: {} };
  await page.addInitScript((session) => sessionStorage.setItem("iqn:character-workspace:session:local", JSON.stringify(session)), { version: 1, key: "local", origin: "world-editor", mode: "edit", workflowId: "workflow-1", parentRoute: "/app/worlds/world-1?tab=characters", expectedWorldRevision: 4, parentDraft: draft, worldContext: draft, rosterSummaries: [], candidate, expiresAt: Date.now() + 60_000 });
  await page.goto(`http://127.0.0.1:${process.env.PLAYWRIGHT_WEB_NEXT_PORT ?? 43174}/app/characters/local`);
  await expect(page.locator("[data-character-review]")).toBeVisible();
  await expect(page.locator("[data-character-review]")).toContainText("story");
  await expect(page.locator("[data-character-stage]:disabled")).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath(`review-${width}.png`), fullPage: true });
  await page.locator('[data-action="accept-character"]').click();
  await expect(page.locator('[name="candidate.profile.story.role"]')).toBeFocused();
  const role = page.locator('[name="candidate.profile.story.role"]');
  await expect(role).toHaveAttribute("placeholder", "e.g., Expedition leader and reluctant guide");
  await expect(page.locator(".character-field-hint", { hasText: "Their current story function" })).toBeVisible();
  const visibility = await role.evaluate((control) => {
    const field = control.getBoundingClientRect();
    const hint = control.parentElement!.querySelector(".character-field-hint")!.getBoundingClientRect();
    const ledger = document.querySelector(".character-progress-ledger")!.getBoundingClientRect();
    return { fieldTop: field.top, fieldBottom: field.bottom, hintBottom: hint.bottom, ledgerTop: ledger.top, viewportHeight: innerHeight };
  });
  expect(visibility.fieldTop).toBeGreaterThanOrEqual(0);
  expect(visibility.fieldBottom).toBeLessThanOrEqual(visibility.ledgerTop);
  expect(visibility.hintBottom).toBeLessThanOrEqual(Math.min(visibility.ledgerTop, visibility.viewportHeight));
  await page.screenshot({ path: info.outputPath(`guidance-${width}.png`), fullPage: true });
  await role.fill("Guide");
  await page.locator('[data-character-stage="mechanics"]').click();
  await page.getByRole("button", { name: "Add statistic" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("textbox", { name: "Name for row 1" }).first()).toBeFocused();
  await page.getByRole("textbox", { name: "Name for row 1" }).first().fill("Resolve");
  await page.getByRole("button", { name: "Remove Resolve" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("button", { name: "Undo remove" })).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("textbox", { name: "Name for row 1" }).first()).toBeFocused();
  await expect(page.getByRole("textbox", { name: "Name for row 1" }).first()).toHaveValue("Resolve");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath(`mechanics-${width}.png`), fullPage: true });
  await page.locator('[data-character-stage="identity"]').click();
  await expect(page.getByText("Character use", { exact: true })).toBeVisible();
  await page.locator('[data-character-use]').selectOption("both");
  await expect(page.getByText("Select by default in starting cast")).toBeVisible();
  await page.locator('[data-character-always-context]').check();
  await page.locator('[data-character-use]').selectOption("supporting");
  await expect(page.locator('[data-character-stage="mechanics"]')).toBeHidden();
  await page.locator("summary", { hasText: "Technical details" }).click();
  const id = page.locator('[name="candidate.id"]');
  await id.scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  const idBox = await id.boundingBox();
  const ledgerBox = await page.locator('.character-progress-ledger').boundingBox();
  expect(idBox!.y + idBox!.height).toBeLessThanOrEqual(ledgerBox!.y);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath(`identity-${width}.png`) });
  await page.locator('[data-character-stage="method"]').click();
  await expect(page.getByRole("heading", { name: "Regenerate with AI" })).toBeVisible();
  await expect(page.locator('[data-character-use]')).toHaveCount(0);
  await expect(page.getByText("Describe changes and generate a replacement draft for review, or return to Review.")).toBeVisible();
  expect(errors).toEqual([]);
});

test("mechanics pagination preserves keyboard focus and reports its range", async ({ page }, info) => {
  await page.setViewportSize({ width: 390, height: 900 });
  const draft = { schemaVersion: 5, world: { title: "Glass Atlas", genre: "", tone: "", premise: "", backgroundStory: "", firstAction: "", rules: "" }, playableCharacters: [], entities: [], relationships: [], rpgStats: [], defaultTriggers: [], eventTriggers: [], assets: [], defaults: {} };
  const candidate = { id: "hero", name: "Ilyra", characterText: "", campaignUse: "playable", startingCastDefault: true, alwaysInContext: false, rpgStats: Array.from({ length: 51 }, (_, i) => ({ name: `Stat ${i + 1}` })), defaultTriggers: [], source: {} };
  await page.addInitScript((session) => sessionStorage.setItem("iqn:character-workspace:session:local", JSON.stringify(session)), { version: 1, key: "local", origin: "world-editor", mode: "edit", workflowId: "workflow-1", parentRoute: "/app/worlds/world-1?tab=characters", expectedWorldRevision: 4, parentDraft: draft, worldContext: draft, rosterSummaries: [], candidate, expiresAt: Date.now() + 60_000 });
  await page.goto(`http://127.0.0.1:${process.env.PLAYWRIGHT_WEB_NEXT_PORT ?? 43174}/app/characters/local`);
  await page.locator('[data-character-stage="mechanics"]').click();
  await expect(page.getByRole("status").filter({ hasText: "Rows 1–50 of 51" })).toBeVisible();
  await page.getByRole("button", { name: "Next rows" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("textbox", { name: "Name for row 51" })).toBeFocused();
  await expect(page.getByRole("status").filter({ hasText: "Rows 51–51 of 51" })).toBeVisible();
  await page.screenshot({ path: info.outputPath("mechanics-pagination-390.png") });
  await page.getByRole("button", { name: "Previous rows" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("textbox", { name: "Name for row 1", exact: true })).toBeFocused();
});


